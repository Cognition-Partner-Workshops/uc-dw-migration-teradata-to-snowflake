-- T-07: CSUM -> SUM OVER (cumulative sum in VW_BRANCH_PERFORMANCE)
-- Verify CUMULATIVE_FEES_YTD is non-decreasing within a branch-year
SELECT COUNT(*) AS VIOLATIONS
FROM (
    SELECT BRANCH_ID, SNAPSHOT_MONTH_KEY, CUMULATIVE_FEES_YTD,
           LAG(CUMULATIVE_FEES_YTD) OVER (
               PARTITION BY BRANCH_ID, FLOOR(SNAPSHOT_MONTH_KEY / 100)
               ORDER BY SNAPSHOT_MONTH_KEY
           ) AS PREV_CUM_FEES
    FROM BANKING_DW.VW_BRANCH_PERFORMANCE
) sub
WHERE PREV_CUM_FEES IS NOT NULL
  AND CUMULATIVE_FEES_YTD < PREV_CUM_FEES;

-- T-08: MAVG -> AVG OVER (moving average 3-month window)
-- Just verify the column exists and has values
SELECT COUNT(*) AS HAS_VALUES
FROM BANKING_DW.VW_BRANCH_PERFORMANCE
WHERE MOVING_AVG_VOLUME_3M IS NOT NULL;

