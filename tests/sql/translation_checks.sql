-- T-01: CASESPECIFIC handling — compare UPPER(CITY) vs exact match
SELECT COUNT(*) AS CASE_DIFFS
FROM BANKING_DW.DIM_CUSTOMER
WHERE CITY != UPPER(CITY) AND CITY != LOWER(CITY);

-- T-02: ZEROIFNULL
SELECT ZEROIFNULL(NULL) AS RESULT;

-- T-03: NULLIFZERO
SELECT NULLIFZERO(0) AS RESULT;

-- T-04: QUALIFY clause — one row per CUSTOMER_ID
SELECT COUNT(*) AS ROW_COUNT
FROM (
    SELECT CUSTOMER_ID,
           ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY EFFECTIVE_FROM DESC) AS RN
    FROM BANKING_DW.DIM_CUSTOMER
    QUALIFY RN = 1
);

-- T-05: HASH() as HASHROW replacement
SELECT COUNT(*) AS NULL_HASHES
FROM BANKING_DW.FACT_TRANSACTION
WHERE HASH(TRANSACTION_ID, TRANSACTION_DATE) IS NULL;

