-- Port of check 1 in data/validation/checksum_queries.sql (row count per table).
-- SEL -> SELECT. Teradata types a UNION column from its first branch ('DIM_CUSTOMER' ->
-- VARCHAR(12)) and, in TERA mode, silently truncates longer labels; LEFT(..., 12) keeps that
-- legacy output (FACT_TRANSAC, FACT_MONTHLY) and ORDER BY 1 sorts the truncated labels.
SELECT LEFT(TABLE_NAME, 12) AS TABLE_NAME, ROW_COUNT
FROM (
SELECT 'DIM_CUSTOMER' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM BANKING_DW.BANKING_DW.DIM_CUSTOMER
UNION ALL
SELECT 'DIM_ACCOUNT', COUNT(*)
FROM BANKING_DW.BANKING_DW.DIM_ACCOUNT
UNION ALL
SELECT 'DIM_PRODUCT', COUNT(*)
FROM BANKING_DW.BANKING_DW.DIM_PRODUCT
UNION ALL
SELECT 'DIM_BRANCH', COUNT(*)
FROM BANKING_DW.BANKING_DW.DIM_BRANCH
UNION ALL
SELECT 'DIM_DATE', COUNT(*)
FROM BANKING_DW.BANKING_DW.DIM_DATE
UNION ALL
SELECT 'FACT_TRANSACTION', COUNT(*)
FROM BANKING_DW.BANKING_DW.FACT_TRANSACTION
UNION ALL
SELECT 'FACT_MONTHLY_SNAPSHOT', COUNT(*)
FROM BANKING_DW.BANKING_DW.FACT_MONTHLY_ACCOUNT_SNAPSHOT
) AS counts
ORDER BY 1
