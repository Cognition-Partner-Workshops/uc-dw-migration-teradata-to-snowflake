-- Seed diagnostics only, not an approved repair or a macro result.
WITH populations AS (
    SELECT 'summary_candidates' AS POPULATION
    UNION ALL SELECT 'alert_candidates'
), candidates AS (
    SELECT 'summary_candidates' AS POPULATION,
           ft.ACCOUNT_KEY, ft.TRANSACTION_TS, ft.RUNNING_BALANCE
    FROM BANKING_DW.DIM_ACCOUNT a
    JOIN BANKING_DW.FACT_TRANSACTION ft ON a.ACCOUNT_KEY = ft.ACCOUNT_KEY
    WHERE a.CURRENT_FLAG = 'Y' AND a.ACCOUNT_STATUS = 'ACTIVE'
      AND ft.TRANSACTION_DATE = $AS_OF_DATE::DATE
    UNION ALL
    SELECT 'alert_candidates', ft.ACCOUNT_KEY, ft.TRANSACTION_TS, ft.RUNNING_BALANCE
    FROM BANKING_DW.DIM_ACCOUNT a
    JOIN BANKING_DW.DIM_CUSTOMER c ON a.CUSTOMER_ID = c.CUSTOMER_ID AND c.CURRENT_FLAG = 'Y'
    JOIN BANKING_DW.FACT_TRANSACTION ft ON a.ACCOUNT_KEY = ft.ACCOUNT_KEY
    WHERE a.CURRENT_FLAG = 'Y' AND a.ACCOUNT_TYPE NOT IN ('CREDIT_CARD', 'LOAN')
      AND ft.TRANSACTION_DATE = $AS_OF_DATE::DATE AND ft.RUNNING_BALANCE < 0
), buckets AS (
    SELECT POPULATION, ACCOUNT_KEY, TRANSACTION_TS,
           COUNT(*) AS ROWS_AT_TS,
           COUNT(DISTINCT RUNNING_BALANCE) + IFF(COUNT_IF(RUNNING_BALANCE IS NULL) > 0, 1, 0)
               AS BALANCE_VARIANTS,
           DENSE_RANK() OVER (
               PARTITION BY POPULATION, ACCOUNT_KEY ORDER BY TRANSACTION_TS DESC NULLS LAST
           ) AS TS_RANK
    FROM candidates
    GROUP BY POPULATION, ACCOUNT_KEY, TRANSACTION_TS
)
SELECT p.POPULATION,
       COALESCE(SUM(b.ROWS_AT_TS), 0) AS ELIGIBLE_ROWS,
       COUNT(DISTINCT b.ACCOUNT_KEY) AS ELIGIBLE_ACCOUNTS,
       COALESCE(COUNT_IF(b.ROWS_AT_TS > 1), 0) AS TIED_TIMESTAMP_GROUPS,
       COALESCE(SUM(IFF(b.ROWS_AT_TS > 1, b.ROWS_AT_TS, 0)), 0) AS ROWS_IN_TIES,
       COALESCE(COUNT_IF(b.TS_RANK = 1 AND b.ROWS_AT_TS > 1), 0) AS LATEST_TIED_ACCOUNTS,
       COALESCE(COUNT_IF(b.TS_RANK = 1 AND b.BALANCE_VARIANTS > 1), 0)
           AS LATEST_CONFLICTING_BALANCE_ACCOUNTS
FROM populations p
LEFT JOIN buckets b ON p.POPULATION = b.POPULATION
GROUP BY p.POPULATION
ORDER BY p.POPULATION;
