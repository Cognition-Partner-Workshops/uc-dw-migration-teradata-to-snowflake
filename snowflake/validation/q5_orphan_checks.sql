-- Port of check 5 in data/validation/checksum_queries.sql (referential integrity).
-- SEL -> SELECT. NOT IN keeps its three-valued semantics on both engines (a NULL key in
-- the subquery makes the predicate unknown). The UNION column takes the first branch's type
-- ('ORPHAN_TXN_ACCOUNT' -> VARCHAR(18)) and Teradata truncates longer labels; LEFT(..., 18)
-- keeps that legacy output (ORPHAN_TXN_CUSTOME, ORPHAN_SNAP_ACCOUN).
SELECT LEFT(CHECK_NAME, 18) AS CHECK_NAME, ORPHAN_COUNT
FROM (
SELECT 'ORPHAN_TXN_ACCOUNT' AS CHECK_NAME,
       COUNT(*) AS ORPHAN_COUNT
FROM BANKING_DW.BANKING_DW.FACT_TRANSACTION ft
WHERE ft.ACCOUNT_KEY NOT IN (
    SELECT ACCOUNT_KEY FROM BANKING_DW.BANKING_DW.DIM_ACCOUNT
)
UNION ALL
SELECT 'ORPHAN_TXN_CUSTOMER',
       COUNT(*)
FROM BANKING_DW.BANKING_DW.FACT_TRANSACTION ft
WHERE ft.CUSTOMER_KEY NOT IN (
    SELECT CUSTOMER_KEY FROM BANKING_DW.BANKING_DW.DIM_CUSTOMER
)
UNION ALL
SELECT 'ORPHAN_SNAP_ACCOUNT',
       COUNT(*)
FROM BANKING_DW.BANKING_DW.FACT_MONTHLY_ACCOUNT_SNAPSHOT snap
WHERE snap.ACCOUNT_KEY NOT IN (
    SELECT ACCOUNT_KEY FROM BANKING_DW.BANKING_DW.DIM_ACCOUNT
)
) AS orphans
