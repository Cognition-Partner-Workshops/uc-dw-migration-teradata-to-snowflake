{{ config(alias='STG_TRANSACTION_ERRORS') }}

select
    cast(TRANSACTION_ID as NUMBER(19,0)) as TRANSACTION_ID,
    cast(ACCOUNT_ID as VARCHAR(20)) as ACCOUNT_ID,
    cast(TRANSACTION_DATE as DATE) as TRANSACTION_DATE,
    cast(TRANSACTION_TIME as TIME(0)) as TRANSACTION_TIME,
    cast(TRANSACTION_TYPE as VARCHAR(20)) as TRANSACTION_TYPE,
    cast(TRANSACTION_SUBTYPE as VARCHAR(30)) as TRANSACTION_SUBTYPE,
    cast(CHANNEL as VARCHAR(20)) as CHANNEL,
    cast(TRANSACTION_AMOUNT as DECIMAL(15,2)) as TRANSACTION_AMOUNT,
    cast(CURRENCY_CODE as CHAR(3)) as CURRENCY_CODE,
    cast(MERCHANT_ID as VARCHAR(20)) as MERCHANT_ID,
    cast(MERCHANT_NAME as VARCHAR(100)) as MERCHANT_NAME,
    cast(MERCHANT_CATEGORY as VARCHAR(4)) as MERCHANT_CATEGORY,
    cast(COUNTERPARTY_ACCT as VARCHAR(20)) as COUNTERPARTY_ACCT,
    cast(REFERENCE_NUMBER as VARCHAR(30)) as REFERENCE_NUMBER,
    cast(DESCRIPTION_TEXT as VARCHAR(200)) as DESCRIPTION_TEXT,
    cast(POSTING_DATE as DATE) as POSTING_DATE,
    cast(VALUE_DATE as DATE) as VALUE_DATE,
    cast(LOAD_DATE as DATE) as LOAD_DATE,
    cast(ERROR_REASON as VARCHAR(50)) as ERROR_REASON,
    cast(BATCH_ID as NUMBER(19,0)) as BATCH_ID
from {{ source('td_source', 'STG_TRANSACTION_ERRORS') }}
union all
select
    cast(s.TRANSACTION_ID as NUMBER(19,0)) as TRANSACTION_ID,
    cast(s.ACCOUNT_ID as VARCHAR(20)) as ACCOUNT_ID,
    cast(s.TRANSACTION_DATE as DATE) as TRANSACTION_DATE,
    cast(s.TRANSACTION_TIME as TIME(0)) as TRANSACTION_TIME,
    cast(s.TRANSACTION_TYPE as VARCHAR(20)) as TRANSACTION_TYPE,
    cast(s.TRANSACTION_SUBTYPE as VARCHAR(30)) as TRANSACTION_SUBTYPE,
    cast(s.CHANNEL as VARCHAR(20)) as CHANNEL,
    cast(s.TRANSACTION_AMOUNT as DECIMAL(15,2)) as TRANSACTION_AMOUNT,
    cast(s.CURRENCY_CODE as CHAR(3)) as CURRENCY_CODE,
    cast(s.MERCHANT_ID as VARCHAR(20)) as MERCHANT_ID,
    cast(s.MERCHANT_NAME as VARCHAR(100)) as MERCHANT_NAME,
    cast(s.MERCHANT_CATEGORY as VARCHAR(4)) as MERCHANT_CATEGORY,
    cast(s.COUNTERPARTY_ACCT as VARCHAR(20)) as COUNTERPARTY_ACCT,
    cast(s.REFERENCE_NUMBER as VARCHAR(30)) as REFERENCE_NUMBER,
    cast(s.DESCRIPTION_TEXT as VARCHAR(200)) as DESCRIPTION_TEXT,
    cast(s.POSTING_DATE as DATE) as POSTING_DATE,
    cast(s.VALUE_DATE as DATE) as VALUE_DATE,
    cast(s.LOAD_DATE as DATE) as LOAD_DATE,
    cast('INVALID_ACCOUNT' as VARCHAR(50)) as ERROR_REASON,
    cast({{ batch_id() }} as NUMBER(19,0)) as BATCH_ID
from {{ ref('stg_transactions') }} s
where s.LOAD_DATE = {{ run_day() }}
and s.ACCOUNT_ID not in (select ACCOUNT_ID from {{ ref('dim_account') }} where CURRENT_FLAG = 'Y')
