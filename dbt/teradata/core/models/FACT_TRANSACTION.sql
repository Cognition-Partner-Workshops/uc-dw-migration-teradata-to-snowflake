WITH inserted (TRANSACTION_ID, TRANSACTION_DATE, TRANSACTION_TIME, TRANSACTION_TS, ACCOUNT_KEY, CUSTOMER_KEY, PRODUCT_ID, BRANCH_ID, DATE_KEY, TRANSACTION_TYPE, TRANSACTION_SUBTYPE, CHANNEL, TRANSACTION_AMOUNT, TRANSACTION_CURRENCY, BASE_CURRENCY_AMOUNT, EXCHANGE_RATE, MERCHANT_ID, MERCHANT_NAME, MERCHANT_CATEGORY, COUNTERPARTY_ACCT, REFERENCE_NUMBER, DESCRIPTION_TEXT, IS_INTERNATIONAL, POSTING_DATE, VALUE_DATE, ETL_BATCH_ID, ETL_INSERT_TS) AS (
SELECT
        stg.TRANSACTION_ID,
        stg.TRANSACTION_DATE,
        stg.TRANSACTION_TIME,
        stg.TRANSACTION_DATE + stg.TRANSACTION_TIME,
        a.ACCOUNT_KEY,
        c.CUSTOMER_KEY,
        a.PRODUCT_ID,
        a.BRANCH_ID,
        CAST(strftime(stg.TRANSACTION_DATE, '%Y%m%d') AS INTEGER),
        stg.TRANSACTION_TYPE,
        stg.TRANSACTION_SUBTYPE,
        stg.CHANNEL,
        stg.TRANSACTION_AMOUNT,
        stg.CURRENCY_CODE,
        CASE WHEN stg.CURRENCY_CODE <> 'NOK'
             THEN stg.TRANSACTION_AMOUNT * coalesce(fx.EXCHANGE_RATE, 0)
             ELSE stg.TRANSACTION_AMOUNT
        END,
        coalesce(fx.EXCHANGE_RATE, 0),
        stg.MERCHANT_ID,
        stg.MERCHANT_NAME,
        stg.MERCHANT_CATEGORY,
        stg.COUNTERPARTY_ACCT,
        stg.REFERENCE_NUMBER,
        stg.DESCRIPTION_TEXT,
        CASE WHEN stg.CURRENCY_CODE <> 'NOK' THEN 1 ELSE 0 END,
        stg.POSTING_DATE,
        stg.VALUE_DATE,
        {{ var("batch_id") }},
        TIMESTAMP '{{ var("load_timestamp") }}'
    FROM {{ ref('STG_TRANSACTIONS') }} stg
    INNER JOIN {{ ref('DIM_ACCOUNT') }} a
        ON stg.ACCOUNT_ID = a.ACCOUNT_ID
       AND a.CURRENT_FLAG = 'Y'
    INNER JOIN {{ ref('DIM_CUSTOMER') }} c
        ON a.CUSTOMER_ID = c.CUSTOMER_ID
       AND c.CURRENT_FLAG = 'Y'
    LEFT JOIN {{ ref('DIM_EXCHANGE_RATES') }} fx
        ON stg.CURRENCY_CODE = fx.FROM_CURRENCY
       AND fx.TO_CURRENCY = 'NOK'
       AND stg.TRANSACTION_DATE = fx.RATE_DATE
    WHERE stg.LOAD_DATE = DATE '{{ var("as_of_date") }}'
      AND stg.ACCOUNT_ID IN (
          SELECT ACCOUNT_ID FROM {{ ref('DIM_ACCOUNT') }} WHERE CURRENT_FLAG = 'Y'
      )
)
SELECT
    CAST(TRANSACTION_ID AS BIGINT) AS TRANSACTION_ID,
    CAST(TRANSACTION_DATE AS DATE) AS TRANSACTION_DATE,
    CAST(TRANSACTION_TIME AS TIME) AS TRANSACTION_TIME,
    CAST(TRANSACTION_TS AS TIMESTAMP) AS TRANSACTION_TS,
    CAST(ACCOUNT_KEY AS BIGINT) AS ACCOUNT_KEY,
    CAST(CUSTOMER_KEY AS BIGINT) AS CUSTOMER_KEY,
    CAST(PRODUCT_ID AS INTEGER) AS PRODUCT_ID,
    CAST(BRANCH_ID AS INTEGER) AS BRANCH_ID,
    CAST(DATE_KEY AS INTEGER) AS DATE_KEY,
    CAST(TRANSACTION_TYPE AS VARCHAR(20)) AS TRANSACTION_TYPE,
    CAST(TRANSACTION_SUBTYPE AS VARCHAR(30)) AS TRANSACTION_SUBTYPE,
    CAST(CHANNEL AS VARCHAR(20)) AS CHANNEL,
    CAST(TRANSACTION_AMOUNT AS DECIMAL(15,2)) AS TRANSACTION_AMOUNT,
    CAST(TRANSACTION_CURRENCY AS CHAR(3)) AS TRANSACTION_CURRENCY,
    CAST(BASE_CURRENCY_AMOUNT AS DECIMAL(15,2)) AS BASE_CURRENCY_AMOUNT,
    CAST(EXCHANGE_RATE AS DECIMAL(12,6)) AS EXCHANGE_RATE,
    CAST(RUNNING_BALANCE AS DECIMAL(15,2)) AS RUNNING_BALANCE,
    CAST(MERCHANT_ID AS VARCHAR(20)) AS MERCHANT_ID,
    CAST(MERCHANT_NAME AS VARCHAR(100)) AS MERCHANT_NAME,
    CAST(MERCHANT_CATEGORY AS VARCHAR(4)) AS MERCHANT_CATEGORY,
    CAST(COUNTERPARTY_ACCT AS VARCHAR(20)) AS COUNTERPARTY_ACCT,
    CAST(REFERENCE_NUMBER AS VARCHAR(30)) AS REFERENCE_NUMBER,
    CAST(DESCRIPTION_TEXT AS VARCHAR(200)) AS DESCRIPTION_TEXT,
    CAST(IS_INTERNATIONAL AS SMALLINT) AS IS_INTERNATIONAL,
    CAST(IS_FLAGGED AS SMALLINT) AS IS_FLAGGED,
    CAST(FLAG_REASON AS VARCHAR(50)) AS FLAG_REASON,
    CAST(POSTING_DATE AS DATE) AS POSTING_DATE,
    CAST(VALUE_DATE AS DATE) AS VALUE_DATE,
    CAST(ETL_BATCH_ID AS BIGINT) AS ETL_BATCH_ID,
    CAST(ETL_INSERT_TS AS TIMESTAMP) AS ETL_INSERT_TS
FROM {{ source('td_src_core', 'FACT_TRANSACTION') }}
UNION ALL
SELECT
    CAST(TRANSACTION_ID AS BIGINT) AS TRANSACTION_ID,
    CAST(TRANSACTION_DATE AS DATE) AS TRANSACTION_DATE,
    CAST(TRANSACTION_TIME AS TIME) AS TRANSACTION_TIME,
    CAST(TRANSACTION_TS AS TIMESTAMP) AS TRANSACTION_TS,
    CAST(ACCOUNT_KEY AS BIGINT) AS ACCOUNT_KEY,
    CAST(CUSTOMER_KEY AS BIGINT) AS CUSTOMER_KEY,
    CAST(PRODUCT_ID AS INTEGER) AS PRODUCT_ID,
    CAST(BRANCH_ID AS INTEGER) AS BRANCH_ID,
    CAST(DATE_KEY AS INTEGER) AS DATE_KEY,
    CAST(TRANSACTION_TYPE AS VARCHAR(20)) AS TRANSACTION_TYPE,
    CAST(TRANSACTION_SUBTYPE AS VARCHAR(30)) AS TRANSACTION_SUBTYPE,
    CAST(CHANNEL AS VARCHAR(20)) AS CHANNEL,
    CAST(TRANSACTION_AMOUNT AS DECIMAL(15,2)) AS TRANSACTION_AMOUNT,
    CAST(TRANSACTION_CURRENCY AS CHAR(3)) AS TRANSACTION_CURRENCY,
    CAST(BASE_CURRENCY_AMOUNT AS DECIMAL(15,2)) AS BASE_CURRENCY_AMOUNT,
    CAST(EXCHANGE_RATE AS DECIMAL(12,6)) AS EXCHANGE_RATE,
    CAST(NULL AS DECIMAL(15,2)) AS RUNNING_BALANCE,
    CAST(MERCHANT_ID AS VARCHAR(20)) AS MERCHANT_ID,
    CAST(MERCHANT_NAME AS VARCHAR(100)) AS MERCHANT_NAME,
    CAST(MERCHANT_CATEGORY AS VARCHAR(4)) AS MERCHANT_CATEGORY,
    CAST(COUNTERPARTY_ACCT AS VARCHAR(20)) AS COUNTERPARTY_ACCT,
    CAST(REFERENCE_NUMBER AS VARCHAR(30)) AS REFERENCE_NUMBER,
    CAST(DESCRIPTION_TEXT AS VARCHAR(200)) AS DESCRIPTION_TEXT,
    CAST(IS_INTERNATIONAL AS SMALLINT) AS IS_INTERNATIONAL,
    CAST(0 AS SMALLINT) AS IS_FLAGGED,
    CAST(NULL AS VARCHAR(50)) AS FLAG_REASON,
    CAST(POSTING_DATE AS DATE) AS POSTING_DATE,
    CAST(VALUE_DATE AS DATE) AS VALUE_DATE,
    CAST(ETL_BATCH_ID AS BIGINT) AS ETL_BATCH_ID,
    CAST(ETL_INSERT_TS AS TIMESTAMP) AS ETL_INSERT_TS
FROM inserted
