SELECT
    CAST(PRODUCT_ID AS INTEGER) AS PRODUCT_ID,
    CAST(PRODUCT_CODE AS VARCHAR(20)) AS PRODUCT_CODE,
    CAST(PRODUCT_NAME AS VARCHAR(100)) AS PRODUCT_NAME,
    CAST(PRODUCT_CATEGORY AS VARCHAR(30)) AS PRODUCT_CATEGORY,
    CAST(PRODUCT_SUBCATEGORY AS VARCHAR(50)) AS PRODUCT_SUBCATEGORY,
    CAST(BASE_INTEREST_RATE AS DECIMAL(7,4)) AS BASE_INTEREST_RATE,
    CAST(MIN_BALANCE AS DECIMAL(15,2)) AS MIN_BALANCE,
    CAST(MAX_BALANCE AS DECIMAL(15,2)) AS MAX_BALANCE,
    CAST(FEE_STRUCTURE AS VARCHAR(20)) AS FEE_STRUCTURE,
    CAST(MONTHLY_FEE AS DECIMAL(10,2)) AS MONTHLY_FEE,
    CAST(IS_REGULATED AS SMALLINT) AS IS_REGULATED,
    CAST(REGULATORY_CODE AS VARCHAR(20)) AS REGULATORY_CODE,
    CAST(LAUNCH_DATE AS DATE) AS LAUNCH_DATE,
    CAST(DISCONTINUE_DATE AS DATE) AS DISCONTINUE_DATE,
    CAST(IS_ACTIVE AS SMALLINT) AS IS_ACTIVE,
    CAST(ETL_BATCH_ID AS BIGINT) AS ETL_BATCH_ID,
    CAST(ETL_INSERT_TS AS TIMESTAMP) AS ETL_INSERT_TS
FROM {{ source('td_src_core', 'DIM_PRODUCT') }}
