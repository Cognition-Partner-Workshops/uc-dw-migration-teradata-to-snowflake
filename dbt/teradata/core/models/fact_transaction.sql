{{ config(alias='FACT_TRANSACTION') }}

select
    cast(TRANSACTION_ID as NUMBER(19,0)) as TRANSACTION_ID,
    cast(TRANSACTION_DATE as DATE) as TRANSACTION_DATE,
    cast(TRANSACTION_TIME as TIME(0)) as TRANSACTION_TIME,
    cast(TRANSACTION_TS as TIMESTAMP_NTZ(6)) as TRANSACTION_TS,
    cast(ACCOUNT_KEY as NUMBER(19,0)) as ACCOUNT_KEY,
    cast(CUSTOMER_KEY as NUMBER(19,0)) as CUSTOMER_KEY,
    cast(PRODUCT_ID as NUMBER(10,0)) as PRODUCT_ID,
    cast(BRANCH_ID as NUMBER(10,0)) as BRANCH_ID,
    cast(DATE_KEY as NUMBER(10,0)) as DATE_KEY,
    cast(TRANSACTION_TYPE as VARCHAR(20)) as TRANSACTION_TYPE,
    cast(TRANSACTION_SUBTYPE as VARCHAR(30)) as TRANSACTION_SUBTYPE,
    cast(CHANNEL as VARCHAR(20)) as CHANNEL,
    cast(TRANSACTION_AMOUNT as DECIMAL(15,2)) as TRANSACTION_AMOUNT,
    cast(TRANSACTION_CURRENCY as CHAR(3)) as TRANSACTION_CURRENCY,
    cast(BASE_CURRENCY_AMOUNT as DECIMAL(15,2)) as BASE_CURRENCY_AMOUNT,
    cast(EXCHANGE_RATE as DECIMAL(12,6)) as EXCHANGE_RATE,
    cast(RUNNING_BALANCE as DECIMAL(15,2)) as RUNNING_BALANCE,
    cast(MERCHANT_ID as VARCHAR(20)) as MERCHANT_ID,
    cast(MERCHANT_NAME as VARCHAR(100)) as MERCHANT_NAME,
    cast(MERCHANT_CATEGORY as VARCHAR(4)) as MERCHANT_CATEGORY,
    cast(COUNTERPARTY_ACCT as VARCHAR(20)) as COUNTERPARTY_ACCT,
    cast(REFERENCE_NUMBER as VARCHAR(30)) as REFERENCE_NUMBER,
    cast(DESCRIPTION_TEXT as VARCHAR(200)) as DESCRIPTION_TEXT,
    cast(IS_INTERNATIONAL as NUMBER(5,0)) as IS_INTERNATIONAL,
    cast(IS_FLAGGED as NUMBER(5,0)) as IS_FLAGGED,
    cast(FLAG_REASON as VARCHAR(50)) as FLAG_REASON,
    cast(POSTING_DATE as DATE) as POSTING_DATE,
    cast(VALUE_DATE as DATE) as VALUE_DATE,
    cast(ETL_BATCH_ID as NUMBER(19,0)) as ETL_BATCH_ID,
    cast(ETL_INSERT_TS as TIMESTAMP_NTZ(0)) as ETL_INSERT_TS
from {{ source('td_source', 'FACT_TRANSACTION') }}
union all
select
    cast(s.TRANSACTION_ID as NUMBER(19,0)) as TRANSACTION_ID,
    cast(s.TRANSACTION_DATE as DATE) as TRANSACTION_DATE,
    cast(s.TRANSACTION_TIME as TIME(0)) as TRANSACTION_TIME,
    cast(timestamp_ntz_from_parts(s.TRANSACTION_DATE, s.TRANSACTION_TIME) as TIMESTAMP_NTZ(6)) as TRANSACTION_TS,
    cast(a.ACCOUNT_KEY as NUMBER(19,0)) as ACCOUNT_KEY,
    cast(c.CUSTOMER_KEY as NUMBER(19,0)) as CUSTOMER_KEY,
    cast(a.PRODUCT_ID as NUMBER(10,0)) as PRODUCT_ID,
    cast(a.BRANCH_ID as NUMBER(10,0)) as BRANCH_ID,
    cast(to_number(to_char(s.TRANSACTION_DATE, 'YYYYMMDD')) as NUMBER(10,0)) as DATE_KEY,
    cast(s.TRANSACTION_TYPE as VARCHAR(20)) as TRANSACTION_TYPE,
    cast(s.TRANSACTION_SUBTYPE as VARCHAR(30)) as TRANSACTION_SUBTYPE,
    cast(s.CHANNEL as VARCHAR(20)) as CHANNEL,
    cast(s.TRANSACTION_AMOUNT as DECIMAL(15,2)) as TRANSACTION_AMOUNT,
    cast(s.CURRENCY_CODE as CHAR(3)) as TRANSACTION_CURRENCY,
    cast(case when s.CURRENCY_CODE <> 'NOK' then s.TRANSACTION_AMOUNT * coalesce(fx.EXCHANGE_RATE, 0) else s.TRANSACTION_AMOUNT end as DECIMAL(15,2)) as BASE_CURRENCY_AMOUNT,
    cast(coalesce(fx.EXCHANGE_RATE, 0) as DECIMAL(12,6)) as EXCHANGE_RATE,
    cast(null as DECIMAL(15,2)) as RUNNING_BALANCE,
    cast(s.MERCHANT_ID as VARCHAR(20)) as MERCHANT_ID,
    cast(s.MERCHANT_NAME as VARCHAR(100)) as MERCHANT_NAME,
    cast(s.MERCHANT_CATEGORY as VARCHAR(4)) as MERCHANT_CATEGORY,
    cast(s.COUNTERPARTY_ACCT as VARCHAR(20)) as COUNTERPARTY_ACCT,
    cast(s.REFERENCE_NUMBER as VARCHAR(30)) as REFERENCE_NUMBER,
    cast(s.DESCRIPTION_TEXT as VARCHAR(200)) as DESCRIPTION_TEXT,
    cast(case when s.CURRENCY_CODE <> 'NOK' then 1 else 0 end as NUMBER(5,0)) as IS_INTERNATIONAL,
    cast(0 as NUMBER(5,0)) as IS_FLAGGED,
    cast(null as VARCHAR(50)) as FLAG_REASON,
    cast(s.POSTING_DATE as DATE) as POSTING_DATE,
    cast(s.VALUE_DATE as DATE) as VALUE_DATE,
    cast({{ batch_id() }} as NUMBER(19,0)) as ETL_BATCH_ID,
    cast({{ load_timestamp() }} as TIMESTAMP_NTZ(0)) as ETL_INSERT_TS
from {{ ref('stg_transactions') }} s
join {{ ref('dim_account') }} a on s.ACCOUNT_ID = a.ACCOUNT_ID and a.CURRENT_FLAG = 'Y'
join {{ ref('dim_customer') }} c on a.CUSTOMER_ID = c.CUSTOMER_ID and c.CURRENT_FLAG = 'Y'
left join {{ ref('dim_exchange_rates') }} fx on s.CURRENCY_CODE = fx.FROM_CURRENCY and fx.TO_CURRENCY = 'NOK' and s.TRANSACTION_DATE = fx.RATE_DATE
where s.LOAD_DATE = {{ run_day() }}
and s.ACCOUNT_ID in (select ACCOUNT_ID from {{ ref('dim_account') }} where CURRENT_FLAG = 'Y')
