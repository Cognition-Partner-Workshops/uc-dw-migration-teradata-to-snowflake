SELECT
    CAST(CUSTOMER_ID AS INTEGER) AS CUSTOMER_ID,
    CAST(FIRST_NAME AS VARCHAR(50)) AS FIRST_NAME,
    CAST(LAST_NAME AS VARCHAR(50)) AS LAST_NAME,
    CAST(DATE_OF_BIRTH AS DATE) AS DATE_OF_BIRTH,
    CAST(GENDER AS CHAR(1)) AS GENDER,
    CAST(MARITAL_STATUS AS CHAR(1)) AS MARITAL_STATUS,
    CAST(EMAIL_ADDRESS AS VARCHAR(100)) AS EMAIL_ADDRESS,
    CAST(PHONE_NUMBER AS VARCHAR(20)) AS PHONE_NUMBER,
    CAST(ADDRESS_LINE_1 AS VARCHAR(100)) AS ADDRESS_LINE_1,
    CAST(ADDRESS_LINE_2 AS VARCHAR(100)) AS ADDRESS_LINE_2,
    CAST(CITY AS VARCHAR(50)) AS CITY,
    CAST(STATE_PROVINCE AS VARCHAR(50)) AS STATE_PROVINCE,
    CAST(POSTAL_CODE AS VARCHAR(10)) AS POSTAL_CODE,
    CAST(COUNTRY_CODE AS CHAR(3)) AS COUNTRY_CODE,
    CAST(CUSTOMER_SEGMENT AS VARCHAR(20)) AS CUSTOMER_SEGMENT,
    CAST(RISK_SCORE AS DECIMAL(5,2)) AS RISK_SCORE,
    CAST(CREDIT_RATING AS CHAR(3)) AS CREDIT_RATING,
    CAST(KYC_STATUS AS VARCHAR(15)) AS KYC_STATUS
FROM {{ source('td_src_core', 'STG_CUSTOMER') }}
