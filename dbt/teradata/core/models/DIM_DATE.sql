SELECT
    CAST(DATE_KEY AS INTEGER) AS DATE_KEY,
    CAST(CALENDAR_DATE AS DATE) AS CALENDAR_DATE,
    CAST(DAY_OF_WEEK AS SMALLINT) AS DAY_OF_WEEK,
    CAST(DAY_NAME AS VARCHAR(10)) AS DAY_NAME,
    CAST(DAY_OF_MONTH AS SMALLINT) AS DAY_OF_MONTH,
    CAST(DAY_OF_YEAR AS SMALLINT) AS DAY_OF_YEAR,
    CAST(WEEK_OF_YEAR AS SMALLINT) AS WEEK_OF_YEAR,
    CAST(ISO_WEEK AS SMALLINT) AS ISO_WEEK,
    CAST(MONTH_NUM AS SMALLINT) AS MONTH_NUM,
    CAST(MONTH_NAME AS VARCHAR(15)) AS MONTH_NAME,
    CAST(MONTH_SHORT AS CHAR(3)) AS MONTH_SHORT,
    CAST(QUARTER_NUM AS SMALLINT) AS QUARTER_NUM,
    CAST(QUARTER_NAME AS CHAR(2)) AS QUARTER_NAME,
    CAST(HALF_YEAR AS SMALLINT) AS HALF_YEAR,
    CAST(CALENDAR_YEAR AS SMALLINT) AS CALENDAR_YEAR,
    CAST(FISCAL_YEAR AS SMALLINT) AS FISCAL_YEAR,
    CAST(FISCAL_QUARTER AS SMALLINT) AS FISCAL_QUARTER,
    CAST(IS_WEEKEND AS SMALLINT) AS IS_WEEKEND,
    CAST(IS_NORWEGIAN_HOLIDAY AS SMALLINT) AS IS_NORWEGIAN_HOLIDAY,
    CAST(HOLIDAY_NAME AS VARCHAR(50)) AS HOLIDAY_NAME,
    CAST(IS_BUSINESS_DAY AS SMALLINT) AS IS_BUSINESS_DAY,
    CAST(IS_MONTH_END AS SMALLINT) AS IS_MONTH_END,
    CAST(IS_QUARTER_END AS SMALLINT) AS IS_QUARTER_END,
    CAST(IS_YEAR_END AS SMALLINT) AS IS_YEAR_END,
    CAST(PRIOR_DAY_DATE AS DATE) AS PRIOR_DAY_DATE,
    CAST(NEXT_DAY_DATE AS DATE) AS NEXT_DAY_DATE,
    CAST(SAME_DAY_PREV_YEAR AS DATE) AS SAME_DAY_PREV_YEAR
FROM {{ source('td_src_core', 'DIM_DATE') }}
