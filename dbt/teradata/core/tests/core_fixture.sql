SELECT 'customer identity convention' AS failure
WHERE (SELECT count(*) FROM {{ ref('DIM_CUSTOMER') }}
       WHERE (CUSTOMER_ID = 1002 AND CUSTOMER_KEY = 16 AND CURRENT_FLAG = 'Y')
          OR (CUSTOMER_ID = 2026001 AND CUSTOMER_KEY = 17 AND CURRENT_FLAG = 'Y')) <> 2
UNION ALL
SELECT 'shared new-customer null partition'
WHERE EXISTS (SELECT 1 FROM {{ ref('DIM_CUSTOMER') }} WHERE CUSTOMER_ID = 2026002)
UNION ALL
SELECT 'inserted transaction defaults'
WHERE EXISTS (
    SELECT 1 FROM {{ ref('FACT_TRANSACTION') }}
    WHERE TRANSACTION_ID >= 900000 AND ETL_BATCH_ID = {{ var('batch_id') }}
      AND (IS_FLAGGED <> 0 OR RUNNING_BALANCE IS NOT NULL OR FLAG_REASON IS NOT NULL)
)
UNION ALL
SELECT 'reject reason'
WHERE EXISTS (
    SELECT 1 FROM {{ ref('STG_TRANSACTION_ERRORS') }}
    WHERE BATCH_ID = {{ var('batch_id') }} AND ERROR_REASON <> 'INVALID_ACCOUNT'
)
UNION ALL
SELECT 'matched monthly retained fields'
WHERE EXISTS (
    SELECT 1 FROM {{ ref('FACT_MONTHLY_ACCOUNT_SNAPSHOT') }} t
    JOIN {{ source('td_src_core', 'FACT_MONTHLY_ACCOUNT_SNAPSHOT') }} s
      ON t.ACCOUNT_KEY = s.ACCOUNT_KEY AND t.SNAPSHOT_MONTH_KEY = s.SNAPSHOT_MONTH_KEY
    WHERE t.CUSTOMER_KEY IS DISTINCT FROM s.CUSTOMER_KEY
       OR t.BASE_CURRENCY_CLOSING IS DISTINCT FROM s.BASE_CURRENCY_CLOSING
       OR t.CURRENCY_CODE IS DISTINCT FROM s.CURRENCY_CODE
       OR t.PRODUCT_ID IS DISTINCT FROM s.PRODUCT_ID
       OR t.BRANCH_ID IS DISTINCT FROM s.BRANCH_ID
)
