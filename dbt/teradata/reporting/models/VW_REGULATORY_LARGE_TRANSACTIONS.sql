SELECT
    ft.TRANSACTION_ID,
    ft.TRANSACTION_DATE,
    ft.TRANSACTION_TS,
    c.CUSTOMER_ID,
    c.FIRST_NAME ,
    c.LAST_NAME ,
    c.KYC_STATUS,
    a.ACCOUNT_ID,
    a.ACCOUNT_TYPE,
    ft.TRANSACTION_TYPE,
    ft.TRANSACTION_SUBTYPE,
    ft.TRANSACTION_AMOUNT,
    ft.TRANSACTION_CURRENCY,
    ft.BASE_CURRENCY_AMOUNT,
    ft.MERCHANT_NAME,
    ft.COUNTERPARTY_ACCT,
    ft.IS_INTERNATIONAL,
    ft.REFERENCE_NUMBER,
    ft.DESCRIPTION_TEXT,
    b.BRANCH_NAME,
    b.REGION,
    CASE
        WHEN ft.BASE_CURRENCY_AMOUNT >= 100000 THEN 'THRESHOLD_EXCEEDED'
        WHEN ft.IS_INTERNATIONAL = 1
             AND ft.BASE_CURRENCY_AMOUNT >= 25000 THEN 'INTL_THRESHOLD'
        WHEN ft.IS_FLAGGED = 1 THEN 'FLAGGED_SUSPICIOUS'
        ELSE 'REVIEW'
    END AS REPORTING_CATEGORY,
    md5(cast(ft.TRANSACTION_ID AS VARCHAR) || '|' || to_char(ft.TRANSACTION_DATE, 'YYYY-MM-DD')) AS ROW_HASH,
    ft.ETL_BATCH_ID
FROM {{ source('core', 'FACT_TRANSACTION') }} ft
INNER JOIN {{ source('core', 'DIM_ACCOUNT') }} a
    ON ft.ACCOUNT_KEY = a.ACCOUNT_KEY
   AND a.CURRENT_FLAG = 'Y'
INNER JOIN {{ source('core', 'DIM_CUSTOMER') }} c
    ON ft.CUSTOMER_KEY = c.CUSTOMER_KEY
   AND c.CURRENT_FLAG = 'Y'
LEFT JOIN {{ source('core', 'DIM_BRANCH') }} b
    ON ft.BRANCH_ID = b.BRANCH_ID
WHERE (ft.BASE_CURRENCY_AMOUNT >= 100000
       OR (ft.IS_INTERNATIONAL = 1 AND ft.BASE_CURRENCY_AMOUNT >= 25000)
       OR ft.IS_FLAGGED = 1)
QUALIFY ROW_NUMBER() OVER (PARTITION BY ft.TRANSACTION_ID
                           ORDER BY ft.ETL_BATCH_ID DESC, ft.TRANSACTION_DATE DESC, ft.ACCOUNT_KEY) = 1
