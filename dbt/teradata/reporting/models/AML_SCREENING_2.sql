SELECT
        'RAPID_MOVEMENT' AS PATTERN_TYPE,
        c.CUSTOMER_ID,
        c.FIRST_NAME || ' ' || c.LAST_NAME AS CUSTOMER_NAME,
        a.ACCOUNT_ID,
        cr.CREDIT_DATE,
        cr.CREDIT_AMOUNT,
        dr.DEBIT_DATE,
        dr.DEBIT_AMOUNT,
        (dr.DEBIT_DATE - cr.CREDIT_DATE) AS DAYS_BETWEEN
    FROM {{ source('core', 'DIM_CUSTOMER') }} c
    INNER JOIN {{ source('core', 'DIM_ACCOUNT') }} a
        ON c.CUSTOMER_ID = a.CUSTOMER_ID AND a.CURRENT_FLAG = 'Y'
    INNER JOIN (
        SELECT ACCOUNT_KEY, TRANSACTION_DATE AS CREDIT_DATE,
             BASE_CURRENCY_AMOUNT AS CREDIT_AMOUNT
        FROM {{ source('core', 'FACT_TRANSACTION') }}
        WHERE TRANSACTION_TYPE = 'CREDIT'
          AND BASE_CURRENCY_AMOUNT >= 50000.00
          AND TRANSACTION_DATE BETWEEN (DATE '{{ var("as_of_date") }}' - 30) AND DATE '{{ var("as_of_date") }}'
    ) cr ON a.ACCOUNT_KEY = cr.ACCOUNT_KEY
    INNER JOIN (
        SELECT ACCOUNT_KEY, TRANSACTION_DATE AS DEBIT_DATE,
             BASE_CURRENCY_AMOUNT AS DEBIT_AMOUNT
        FROM {{ source('core', 'FACT_TRANSACTION') }}
        WHERE TRANSACTION_TYPE IN ('DEBIT', 'TRANSFER')
          AND BASE_CURRENCY_AMOUNT >= 50000.00 * 0.9
          AND TRANSACTION_DATE BETWEEN (DATE '{{ var("as_of_date") }}' - 30) AND DATE '{{ var("as_of_date") }}'
    ) dr ON cr.ACCOUNT_KEY = dr.ACCOUNT_KEY
        AND dr.DEBIT_DATE BETWEEN cr.CREDIT_DATE AND cr.CREDIT_DATE + 3
    WHERE c.CURRENT_FLAG = 'Y'
    ORDER BY cr.CREDIT_AMOUNT DESC
