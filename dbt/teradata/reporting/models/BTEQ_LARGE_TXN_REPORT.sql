SELECT
    TRANSACTION_ID,
    TRANSACTION_DATE,
    CUSTOMER_ID,
    FIRST_NAME,
    LAST_NAME,
    KYC_STATUS,
    ACCOUNT_ID,
    ACCOUNT_TYPE,
    TRANSACTION_TYPE,
    TRANSACTION_AMOUNT,
    TRANSACTION_CURRENCY,
    BASE_CURRENCY_AMOUNT,
    IS_INTERNATIONAL,
    REPORTING_CATEGORY,
    MERCHANT_NAME,
    REFERENCE_NUMBER
FROM {{ ref('VW_REGULATORY_LARGE_TRANSACTIONS') }}
WHERE TRANSACTION_DATE BETWEEN (DATE '{{ var("as_of_date") }}' + INTERVAL '-1 MONTH')
                          AND DATE '{{ var("as_of_date") }}'
ORDER BY TRANSACTION_DATE, TRANSACTION_ID
