SELECT
        'BALANCE_SUMMARY' AS CHECK_TYPE,
        ACCOUNT_TYPE,
        CURRENCY_CODE,
        COUNT(*) AS ACCOUNT_COUNT,
        SUM(RUNNING_BALANCE) AS TOTAL_BALANCE,
        AVG(RUNNING_BALANCE) AS AVG_BALANCE,
        MIN(RUNNING_BALANCE) AS MIN_BALANCE,
        MAX(RUNNING_BALANCE) AS MAX_BALANCE
 FROM (SELECT a.ACCOUNT_TYPE, a.CURRENCY_CODE, ft.RUNNING_BALANCE, ft.ACCOUNT_KEY, ft.TRANSACTION_TS, ft.TRANSACTION_ID, ft.ETL_BATCH_ID
    FROM {{ source('core', 'DIM_ACCOUNT') }} a
    INNER JOIN {{ source('core', 'FACT_TRANSACTION') }} ft
        ON a.ACCOUNT_KEY = ft.ACCOUNT_KEY
    WHERE a.CURRENT_FLAG = 'Y'
      AND a.ACCOUNT_STATUS = 'ACTIVE'
      AND ft.TRANSACTION_DATE = DATE '{{ var("as_of_date") }}'
    QUALIFY ROW_NUMBER() OVER (PARTITION BY ft.ACCOUNT_KEY
                               ORDER BY ft.TRANSACTION_TS DESC, ft.TRANSACTION_ID DESC, ft.ETL_BATCH_ID DESC) = 1
) latest
    GROUP BY ACCOUNT_TYPE, CURRENCY_CODE
    ORDER BY ACCOUNT_TYPE, CURRENCY_CODE
