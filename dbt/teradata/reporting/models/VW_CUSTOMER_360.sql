SELECT
    c.CUSTOMER_ID,
    c.FIRST_NAME || ' ' || c.LAST_NAME AS FULL_NAME,
    c.CUSTOMER_SEGMENT,
    c.RISK_SCORE,
    c.CREDIT_RATING,
    c.KYC_STATUS,
    c.ONBOARDING_DATE,
    CAST((DATE '2026-01-31' - c.ONBOARDING_DATE) / 365.25 AS DECIMAL(5,1)) AS TENURE_YEARS,
    coalesce(acct_summary.TOTAL_ACCOUNTS, 0) AS TOTAL_ACCOUNTS,
    coalesce(acct_summary.ACTIVE_ACCOUNTS, 0) AS ACTIVE_ACCOUNTS,
    coalesce(acct_summary.TOTAL_BALANCE, 0) AS TOTAL_BALANCE,
    coalesce(txn_summary.TXN_COUNT_90D, 0) AS TXN_COUNT_LAST_90_DAYS,
    coalesce(txn_summary.TXN_AMOUNT_90D, 0) AS TXN_AMOUNT_LAST_90_DAYS,
    txn_summary.LAST_TXN_DATE,
    txn_summary.PRIMARY_CHANNEL,
    c.CITY,
    c.COUNTRY_CODE
FROM {{ source('core', 'DIM_CUSTOMER') }} c
LEFT JOIN (
    SELECT
        CUSTOMER_ID,
        COUNT(*) AS TOTAL_ACCOUNTS,
        SUM(CASE WHEN ACCOUNT_STATUS = 'ACTIVE' THEN 1 ELSE 0 END) AS ACTIVE_ACCOUNTS,
        SUM(snap.CLOSING_BALANCE) AS TOTAL_BALANCE
    FROM {{ source('core', 'DIM_ACCOUNT') }} a
    LEFT JOIN (SELECT ACCOUNT_KEY, CLOSING_BALANCE FROM {{ source('core', 'FACT_MONTHLY_ACCOUNT_SNAPSHOT') }}
        QUALIFY ROW_NUMBER() OVER (PARTITION BY ACCOUNT_KEY ORDER BY SNAPSHOT_DATE DESC) = 1
    ) snap ON snap.ACCOUNT_KEY = a.ACCOUNT_KEY
    WHERE a.CURRENT_FLAG = 'Y'
    GROUP BY 1
) acct_summary
    ON c.CUSTOMER_ID = acct_summary.CUSTOMER_ID
LEFT JOIN (
    SELECT
        ft.CUSTOMER_KEY,
        COUNT(*) AS TXN_COUNT_90D,
        SUM(ABS(ft.TRANSACTION_AMOUNT)) AS TXN_AMOUNT_90D,
        MAX(ft.TRANSACTION_DATE) AS LAST_TXN_DATE,
        MAX(ft.CHANNEL) AS PRIMARY_CHANNEL
    FROM {{ source('core', 'FACT_TRANSACTION') }} ft
    WHERE ft.TRANSACTION_DATE >= DATE '2026-01-31' - 90
    GROUP BY 1
) txn_summary
    ON c.CUSTOMER_KEY = txn_summary.CUSTOMER_KEY
WHERE c.CURRENT_FLAG = 'Y'
  AND c.IS_ACTIVE = 1
